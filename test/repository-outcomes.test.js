const { describe, test, expect } = require('bun:test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const YAML = require('yaml');
const { checkRepositoryOutcomes } = require('../scripts/check-repository-outcomes');
const { AUDIT_ARTIFACT, auditBdCallSites, renderBdCallSiteAuditMarkdown } = require('../lib/release-readiness');

describe('repository CI outcomes', () => {
  test('missing generated mirror fails a relevant change; unrelated docs do not trigger it', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-outcomes-'));
    try {
      expect(checkRepositoryOutcomes(root, ['docs/example.md'])).toEqual([]);
      expect(checkRepositoryOutcomes(root, ['.agents/skills/example/SKILL.md'])).toContain('Missing committed .agents/skills mirror');
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  test('required CI Gate includes repository outcomes without rerunning Tests on edits', () => {
    const workflow = YAML.parse(fs.readFileSync(path.join(__dirname, '../.github/workflows/test.yml'), 'utf8'));
    const job = workflow.jobs['repository-outcomes'];
    expect(workflow.jobs['ci-gate'].needs).toContain('repository-outcomes');
    expect(workflow.jobs['ci-gate'].steps[0].env.RESULTS).toContain('needs.repository-outcomes.result');
    expect(job.steps.some(step => step.run === 'bun install --frozen-lockfile')).toBe(true);
    expect(job.steps.some(step => step.env?.PR_TITLE)).toBe(false);
    expect(workflow.on.pull_request.types).toEqual(['opened', 'synchronize', 'reopened', 'ready_for_review']);
  });

  test('title edits run an independent conventional-title check', () => {
    const workflow = YAML.parse(fs.readFileSync(path.join(__dirname, '../.github/workflows/pr-title.yml'), 'utf8'));
    const testsWorkflow = YAML.parse(fs.readFileSync(path.join(__dirname, '../.github/workflows/test.yml'), 'utf8'));
    expect(workflow.on.pull_request.types).toEqual(['opened', 'edited', 'synchronize', 'reopened']);
    expect(workflow.permissions).toEqual({ contents: 'read' });
    expect(workflow.concurrency.group).not.toBe(testsWorkflow.concurrency.group);
    const job = workflow.jobs['pr-title'];
    expect(job.steps.some(step => step.run === 'bun install --frozen-lockfile')).toBe(true);
    expect(job.steps.some(step => step.env?.PR_TITLE === '${{ github.event.pull_request.title }}'
      && step.run === "printf '%s\\n' \"$PR_TITLE\" | bun x --no-install commitlint")).toBe(true);
  });

  test('a changed mirror fails and a matching mirror passes without rewriting it', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-mirror-outcomes-'));
    try {
      for (const directory of ['skills/example', '.agents/skills/example']) {
        fs.mkdirSync(path.join(root, directory), { recursive: true });
        fs.writeFileSync(path.join(root, directory, 'SKILL.md'), '---\nname: example\n---\nCanonical\n');
      }
      expect(checkRepositoryOutcomes(root, ['skills/example/SKILL.md'])).toEqual([]);
      const mirror = path.join(root, '.agents/skills/example/SKILL.md');
      fs.writeFileSync(mirror, 'stale');
      expect(checkRepositoryOutcomes(root, ['skills/example/SKILL.md']).some(message => message.includes('Skill drift'))).toBe(true);
      expect(fs.readFileSync(mirror, 'utf8')).toBe('stale');
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  test('D20 freshness rejects missing and stale artifacts and accepts regenerated bytes', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-audit-outcomes-'));
    try {
      const artifact = path.join(root, AUDIT_ARTIFACT);
      expect(checkRepositoryOutcomes(root, [AUDIT_ARTIFACT])).toContain('D20 audit is stale: run forge release regen-audit');
      fs.mkdirSync(path.dirname(artifact), { recursive: true });
      fs.writeFileSync(artifact, renderBdCallSiteAuditMarkdown(auditBdCallSites(root)));
      expect(checkRepositoryOutcomes(root, [AUDIT_ARTIFACT])).toEqual([]);
      fs.writeFileSync(artifact, 'stale');
      expect(checkRepositoryOutcomes(root, [AUDIT_ARTIFACT])).toContain('D20 audit is stale: run forge release regen-audit');
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  test('repository no longer installs local hooks', () => {
    const root = path.join(__dirname, '..');
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    expect(pkg.scripts.prepare).toBeUndefined();
    expect(pkg.devDependencies.lefthook).toBeUndefined();
    expect(fs.existsSync(path.join(root, 'lefthook.yml'))).toBe(false);
    expect(fs.existsSync(path.join(root, '.husky'))).toBe(false);
  });
});
